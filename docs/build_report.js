let figN = 0;
function FIG(file, caption, widthPx = 610) {
  const buf = fs.readFileSync(path.join(ROOT, file));
  const w = buf.readUInt32BE(16), h = buf.readUInt32BE(20);
  figN += 1;
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { before: 120, after: 60 }, keepNext: true,
      children: [new ImageRun({ type: "png", data: buf, transformation: { width: widthPx, height: Math.round(widthPx * h / w) } })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { line: 300, after: 160 },
      children: [new TextRun({ text: `Рисунок ${figN} — ${caption}`, font: FONT, size: SZ })],
    }),
  ];
}

let tabN = 0;
const border = { style: BorderStyle.SINGLE, size: 4, color: "000000" };
const borders = { top: border, bottom: border, left: border, right: border };

function TABLE(caption, header, rows, widths, opts = {}) {
  tabN += 1;
  const sum = widths.reduce((a, b) => a + b, 0);
  const ws = widths.map((w) => Math.round(w * TEXT_W / sum));
  ws[ws.length - 1] += TEXT_W - ws.reduce((a, b) => a + b, 0);
  // keepNext в ячейках держит таблицу на одной странице (кроме последней строки)
  const cell = (t, i, bold, keep = true) => new TableCell({
    borders, width: { size: ws[i], type: WidthType.DXA }, verticalAlign: VerticalAlign.CENTER,
    margins: { top: 40, bottom: 40, left: 80, right: 80 },
    children: [new Paragraph({
      keepNext: keep,
      alignment: (opts.center || []).includes(i) ? AlignmentType.CENTER : AlignmentType.LEFT,
      children: [new TextRun({ text: String(t), font: FONT, size: SZ_T, bold })],
    })],
  });
  return [
    new Paragraph({
      spacing: { line: 300, before: 160, after: 60 }, keepNext: true,
      children: [new TextRun({ text: `Таблица ${tabN} — ${caption}`, font: FONT, size: SZ })],
    }),
    new Table({
      width: { size: TEXT_W, type: WidthType.DXA }, columnWidths: ws,
      rows: [
        new TableRow({ tableHeader: true, children: header.map((t, i) => cell(t, i, true)) }),
        ...rows.map((r, k) => new TableRow({ cantSplit: true,
          children: r.map((t, i) => cell(t, i, false, k < rows.length - 1)) })),
      ],
    }),
    new Paragraph({ spacing: { after: 120 }, children: [] }),
  ];
}


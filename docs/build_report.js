function runs(text, extra = {}) {
  // **жирный** внутри строки
  const parts = text.split(/(\*\*[^*]+\*\*)/);
  return parts.filter(Boolean).map((p) =>
    p.startsWith("**") ? new TextRun({ text: p.slice(2, -2), bold: true, font: FONT, size: SZ, ...extra })
      : new TextRun({ text: p, font: FONT, size: SZ, ...extra }));
}

